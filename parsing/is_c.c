int	is_c(char **str)
{
	int	i;
	int	j;
	int	count;

	i = 0;
	j = 0;
	count = 0;
	while (str[i])
	{
		while (str[i][j])
		{
			if (str[i][j] == 'C')
				count += 1;
			j++;
		}
		i++;
	}
	if (count < 1)
		return (0);
	return (1);
}
