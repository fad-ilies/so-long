#include "so_long.h"

int	first_col_1(char **str)
{
	int	i;
	int	j;

	i = 0;
	j = 0;
	if (!str || !str[i][0])
		return (0);
	while (str[i][0])
	{
		if (str[i][0] != '1')
			return (0);
		i++;
	}
	return (1);
}

