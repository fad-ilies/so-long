int	last_line_1(char **str)
{
	int	i;
	int	j;

	i = 0;
	while (**str)
		i++;
	j = 0;
	while (str[i][j])
	{
		if (str[i][j] != '1')
			return (0);
		j++;
	}
	return (1);
}
