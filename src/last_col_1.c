int	last_col_1(char **str)
{
	int	i;
	int	j;

	i = 0;
	j = 0;
	while (str[i][j])
	{
		if (str[i][j + 1] == '\n')
		{
			if (str[i][j] != '1')
				return (0);
			i++;
		}
	}
	return (1);
}
