#include "so_long.h"

int	first_line_1(char **str)
{
	int	i;
	int	j;

	i = 0;
	j = 0;
	if (!str || !str[0][j])
		return (0);
	while (str[0][j])
	{
		if (str[0][j] != '1')
			return (0);
		j++;
	}
	return (1);
}
